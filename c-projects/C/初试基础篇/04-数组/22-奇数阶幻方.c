#include <stdio.h>

int main() {
    int n;
    scanf("%d", &n);
    
    // 题目数据最大是39，开40即可
    int a[40][40] = {0}; 
    
    // 1 放在第一行中间 (0-based)
    int r = 0;
    int c = n / 2;
    a[r][c] = 1;
    
    // 从2开始填到 n*n
    for (int k = 2; k <= n * n; k++) {
        // 规则1：在第一行但不在最后一列
        if (r == 0 && c != n - 1) {
            r = n - 1;
            c = c + 1;
        } 
        // 规则2：在最后一列但不在第一行
        else if (c == n - 1 && r != 0) {
            r = r - 1;
            c = 0;
        } 
        // 规则3：在第一行最后一列
        else if (r == 0 && c == n - 1) {
            r = r + 1;
            // c 保持不动，就是 n-1
        } 
        // 规则4：既不在第一行，也不在最后一列
        else {
            // 如果右上方（r-1, c+1）还没有填数
            if (a[r - 1][c + 1] == 0) {
                r = r - 1;
                c = c + 1;
            } 
            // 否则填在正下方
            else {
                r = r + 1;
                // c 保持不动
            }
        }
        
        a[r][c] = k;
    }
    
    // 输出矩阵
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            printf("%d ", a[i][j]);
        }
        printf("\n");
    }
    
    return 0;
}