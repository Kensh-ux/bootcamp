// 现有一个长宽高分别为w,x,h组成的实心玻璃立方体,可以认为是由1×1×1的数个小方块组成的,每个
// 小方块都有一个坐标(i,j,k)。现在需要进行q次切割。每次切割给出(x1,y1,z1),(x2,y2,z2)这6个参
// 数,保证xC1≤x2,y1≤y2,z1≤z2;每次切割时,使用激光工具切出一个立方体空洞,空洞的壁平行于
// 立方体的面,空洞的对角点就是给出的切割参数的两个点。
// 换句话说,所有满足x1 ≤i≤x2,y1≤j≤y2,z1≤k≤z2的小方块(i,j,k)的点都会被激光蒸发。
// 例如有一个4×4×4的大方块,其体积为64;给出参数(1,1,1),(2,2,2)时,对应的8块小方块就会被
// 蒸发,剩下56个小方块。现在想知道经过所有切割操作后,剩下的工艺品还剩下多少格小方块的体积?

// 输入格式
// 第一行三个正整数w,x,h。
// 第二行一个正整数q。
// 接下来q行,每行六个整数(x1,y1,z1),(x2,y2,z2)。

// 输出格式
// 输出一个整数表示答案。

// 这道题看似是个几何题，其实是“模拟题”。考的就是会不会用三重循环去枚举所有小方块，以及会不会用标记数组。

// 不需要去算重叠的体积（那是数学做法，代码会写死）。直接用标记法，哪怕挖一百次，重叠了就重叠了，反正只要标记为1就算挖过了。这就是“暴力破解”。等把这种暴力思维练熟了，再去看算法书，就会觉得那些高大上的算法其实都是在“优化暴力”。

#include <stdio.h>

int main() {
    int w, x, h; // 长、宽、高
    scanf("%d %d %d", &w, &x, &h);
    
    // 题目保证最大是20，我们开大一点，直接用坐标当下标
    // 0代表还在，1代表被挖走
    int block[25][25][25] = {0}; 
    
    int q;
    scanf("%d", &q);
    
    for(int t = 0; t < q; t++) {
        int x1, y1, z1, x2, y2, z2;
        scanf("%d %d %d %d %d %d", &x1, &y1, &z1, &x2, &y2, &z2);
        
        // 三重循环暴力把这个区域里的方块全部标记为1
        for(int i = x1; i <= x2; i++) {
            for(int j = y1; j <= y2; j++) {
                for(int k = z1; k <= z2; k++) {
                    block[i][j][k] = 1; // 挖掉
                }
            }
        }
    }
    
    // 最后遍历整个大盒子，数一数还有多少个 0
    int remaining = 0;
    for(int i = 1; i <= w; i++) {
        for(int j = 1; j <= x; j++) {
            for(int k = 1; k <= h; k++) {
                if(block[i][j][k] == 0) {
                    remaining++;
                }
            }
        }
    }
    
    printf("%d\n", remaining);
    return 0;
}