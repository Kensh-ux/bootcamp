#include <stdio.h>

int main() {
    int n;
    scanf("%d", &n);
    
    // X 最大是 100，我们从 100 开始往下枚举
    for (int x = 100; x >= 1; x--) {
        int rem = n - 364 * x; // 剩余需要靠 K 填补的钱
        
        // 如果剩余的钱能刚好被 1092 整除，并且 K > 0 (即 rem > 0)
        if (rem > 0 && rem % 1092 == 0) {
            int k = rem / 1092;
            printf("%d\n%d\n", x, k);
            return 0; // 找到答案立刻结束，因为这是 X 最大的解
        }
    }
    
    return 0;
}

